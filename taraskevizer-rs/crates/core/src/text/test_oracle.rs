/// Pre-compiled old implementation (built once per test, like the
/// production `LazyLock` + regex cache — compilation cost excluded).
pub(crate) struct OldAbc {
    lower: FancyDict,
    upper: Option<FancyDict>,
}

pub(crate) fn old_abc(abc: Alphabet) -> OldAbc {
    let upper_table = upper_table(abc);
    OldAbc {
        lower: FancyDict::new(lower_table(abc)),
        upper: (!upper_table.is_empty()).then(|| FancyDict::new(upper_table)),
    }
}

impl OldAbc {
    pub(crate) fn lower(&self, text: &str) -> String {
        self.lower.replace_all(text)
    }

    pub(crate) fn full(&self, text: &str) -> String {
        match &self.upper {
            Some(u) => u.replace_all(&self.lower(text)),
            None => self.lower(text),
        }
    }
}

fn lower_table(abc: Alphabet) -> &'static [(&'static str, &'static str)] {
    match abc {
        Alphabet::Cyrillic => &[],
        Alphabet::Latin => LAT_LOWER,
        Alphabet::LatinJi => JI_LOWER,
        Alphabet::Arabic => AR_LOWER,
    }
}

fn upper_table(abc: Alphabet) -> &'static [(&'static str, &'static str)] {
    match abc {
        Alphabet::Cyrillic => &[],
        Alphabet::Latin => LAT_UPPER,
        Alphabet::LatinJi => JI_UPPER,
        Alphabet::Arabic => &[],
    }
}
